"""Package a compiled program for a bare-metal RISC-V host and build the host ELF."""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from typing import Any

from . import toolchain

GUARD_BYTES = 32
# Diagnostic build, as in examples/handoff: no bitstream is bound and DRAM is
# assumed coherent.
DEFINES = ["-DATLAS_DIAGNOSTIC_ALLOW_UNBOUND=1", "-DATLAS_DIAGNOSTIC_ASSUME_COHERENT=1",
           "-DATLAS_MAX_POLLS=10000000", "-DATLAS_STANDALONE_MEMOPS=1"]
COMMON_FLAGS = ["-mabi=lp64", "-mcmodel=medany", "-O2", "-ffreestanding", "-fno-builtin",
                "-fno-stack-protector", "-fno-pic", "-nostdlib"]


def layout(manifest: dict[str, Any]) -> dict[str, Any]:
    """The reset-entry DRAM layout implied by the importer's slot and output addresses."""
    slots = manifest["input_slots"]
    outputs = manifest["outputs"]
    input_start = min(slot["dram_address"] for slot in slots)
    input_end = max(slot["dram_address"] + slot["reserved_slot_bytes"] for slot in slots)
    output_start = outputs[0]["dram_address"]
    output_end = max(row["dram_address"] + row["payload_bytes"] for row in outputs)
    return {
        "schema": "atlas.reset-entry-layout.v1",
        "selected_rtl_revision": manifest["selected_rtl_revision"],
        "dram_window_base": hex(input_start & ~0xFFFFF),
        "regions": [
            {"name": "input_and_constants", "kind": "input",
             "address": hex(input_start), "size_bytes": input_end - input_start},
            {"name": "output", "kind": "output",
             "address": hex(output_start), "size_bytes": output_end - output_start},
            {"name": "output_guard", "kind": "guard",
             "address": hex(output_end), "size_bytes": GUARD_BYTES},
        ],
    }


def _importer() -> Any:
    """The importer's own packers, so host inputs use the encoding the program expects."""
    spec = importlib.util.spec_from_file_location(
        "atlas_compile_linalg_tile", toolchain.tool("compile_atlas_linalg_tile.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inputs_header(manifest: dict[str, Any], inputs: dict[str, Any]) -> str:
    importer = _importer()
    lines = ["/* Generated by atlasc from the example inputs. Do not edit. */",
             "#ifndef ATLAS_RUN_INPUTS_H", "#define ATLAS_RUN_INPUTS_H",
             '#include "atlas_captured_data.h"']
    blobs = []
    for slot in manifest["input_slots"]:
        if slot["source_kind"] != "input":
            continue
        name = slot["source_key"]
        if name not in inputs:
            raise ValueError(f"no example value for graph input {name!r}")
        packer = (importer.pack_bias_tile if slot["physical_role"] == "bias_bf16"
                  else importer.pack_fp8_tile)
        data = packer(inputs[name])
        if len(data) != slot["payload_bytes"]:
            raise ValueError(f"input {name!r} packs to {len(data)} bytes, "
                             f"not the slot's {slot['payload_bytes']}")
        symbol = f"atlas_run_input_{len(blobs)}"
        lines.append(f"/* {name}: {slot['physical_role']} */")
        lines.append(f"static const uint8_t {symbol}[{len(data)}] = {{")
        lines.extend("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ","
                     for start in range(0, len(data), 16))
        lines.append("};")
        blobs.append((symbol, slot["dram_address"], len(data)))
    lines.append(f"#define ATLAS_RUN_INPUT_COUNT {len(blobs)}u")
    lines.append("static const atlas_init_blob atlas_run_inputs[ATLAS_RUN_INPUT_COUNT] = {")
    lines.extend(f"    {{0x{address:08x}u, {size}u, {symbol}}},"
                 for symbol, address, size in blobs)
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines)


def compile_elf(cc: str, host: Path, elf: Path) -> None:
    root = toolchain.data_root()
    startup = root / "examples/handoff/captured_attention_mlp"
    runtime = root / "runtime"
    sources = [str(startup / "start.S"), str(runtime / "atlas_run.c"),
               str(runtime / "atlas_host.c")]
    includes = ["-I", str(runtime), "-I", str(host)]
    if "clang" in Path(cc).name:
        command = [cc, "--target=riscv64-unknown-elf", "-march=rv64imac", *COMMON_FLAGS,
                   "-fuse-ld=lld", *DEFINES, *includes, *sources,
                   f"-Wl,-T,{startup / 'link.ld'}", "-Wl,--no-relax", "-o", str(elf)]
    else:
        # GCC 12 and later need the CSR and fence.i extensions named.
        command = [cc, "-march=rv64imac_zicsr_zifencei", *COMMON_FLAGS, "-nostartfiles",
                   *DEFINES, *includes, *sources, "-T", str(startup / "link.ld"),
                   "-Wl,--no-relax", "-o", str(elf)]
    toolchain.run(command, "host ELF link")


def package(compiled: Path, out: Path, inputs: dict[str, Any] | None,
            cc: str | None) -> dict[str, Any]:
    """Capsule and host headers always; the host ELF when there are inputs and a compiler."""
    manifest = json.loads((compiled / "import-manifest.json").read_text())
    layout_path = out / "layout.json"
    layout_path.write_text(json.dumps(layout(manifest), indent=2) + "\n")
    capsule = out / "capsule"
    host = out / "host"
    toolchain.run_tool("atlas_boot_pack.py", "--source", compiled / "atlas-machine.mlir",
                       "--atlas-emit", toolchain.bin_dir() / "atlas-emit",
                       "--layout", layout_path,
                       "--import-manifest", compiled / "import-manifest.json",
                       "--out", capsule, step="boot capsule")
    host.mkdir()
    toolchain.run_tool("atlas_captured_host_data.py", "--compiled", compiled,
                       "--capsule", capsule, "--out", host / "atlas_captured_data.h",
                       step="host data header")
    toolchain.run_tool("atlas_host_embed.py", "--capsule", capsule,
                       "--host-map", toolchain.data_root() / "runtime/selected-host-map.json",
                       "--out", host / "atlas_program.h", step="program header")
    result: dict[str, Any] = {"layout": str(layout_path), "capsule": str(capsule),
                              "headers": str(host), "elf": None}
    if inputs is None:
        result["elf_skipped"] = "no example inputs"
        return result
    (host / "atlas_run_inputs.h").write_text(inputs_header(manifest, inputs))
    if cc is None:
        result["elf_skipped"] = f"no RISC-V compiler ({toolchain.HOST_CC} from Chipyard's riscv-tools)"
        return result
    elf = host / "atlas-host.elf"
    compile_elf(cc, host, elf)
    result["elf"] = str(elf)
    return result
