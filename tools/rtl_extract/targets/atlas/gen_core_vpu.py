#!/usr/bin/env python3
"""Generate AtlasCore's ordered VPU pairs; stdout matches the committed YAML.

Usage: gen_core_vpu.py FACTS_JSON [PAIR_SWEEP_JSON] [--output PATH]
The optional sweep supplies regression values used only by tests. The historical
build/gen_core_vpu.py comment is preserved so existing specs reproduce byte for byte.
"""
import argparse
import json
from pathlib import Path
import sys

import yaml

TARGET = Path(__file__).resolve().parent
MARGIN = 5


def generate(facts, sweep=None, spec_path=TARGET / "vpu.yaml"):
    """Render the spec from decode words, extracted issue ages and optional regressions."""
    spec = yaml.safe_load(spec_path.read_text())
    words = spec["decode"]["words"]
    nia = {r["operation"]: r["next_issue_age"] for r in facts["op_timing"] if r["engine"] == "vpu"}
    if set(words) != set(nia) or len(words) != 29:
        raise ValueError("facts must contain exactly the 29 VPU operations in vpu.yaml")
    VLI = {"vliAll", "vliRow", "vliCol", "vliOne"}
    SETS = {"first": (8, 12, 16), "second": (20, 24, 28)}   # vs1, vs2, vd; physical banks (mod 32) disjoint


    def instruction(op, side):
        vs1, vs2, vd = SETS[side]
        word = words[op] | vd << 7
        return word if op in VLI else word | vs1 << 13 | vs2 << 19


    order = list(words)
    lines = [
        "# All 29x29 ordered VPU pairs on AtlasCore through the decoder cut (targets/atlas/system/core.yaml); every AtlasCore",
        "# assertion is an invariant, so the VPU issue-busy check, MREG bank tracker and MregFile port checks decide. The first",
        "# command uses vs1 8, vs2 12, vd 16 and the second vs1 20, vs2 24, vd 28 (even, disjoint physical MREG banks mod 32);",
        "# unused operand fields are set the same way. fp8pack/fp8unpack take the scale register in vs1 and the source in vs2;",
        "# vli words carry only vd. Each side overrides the instruction word of the carrier operations add / add_hi.",
        "# Gaps run to the first operation's first_free_age plus 5. Generated by build/gen_core_vpu.py from vpu.yaml decode words.",
        "# `as` names the op_timing blocks each side stands for; `relation` states the operand relation every pair satisfies",
        "# (each command's MREG registers lie in physical banks the other's do not use), which pair facts carry to the compiler.",
        "engine: core",
        "description: Every ordered VPU operation pair, second issued g ages after the first; all AtlasCore assertions checked.",
        "equivalent:",
        "  vpu_read: [vpu_read0, vpu_read1]",
        "  vpu_write: [vpu_write0, vpu_write1]",
        "shared:",
        "  - {input: instruction, reason: one instruction per age through the decoder; commands never share an age}",
        "  - {input: fire, reason: issue strobe of that instruction}",
        "  - {input: address, reason: VLS address operand of that instruction}",
        "  - {path: mreg, reason: MREG file; per-bank port conflicts are MregFile invariants}",
        "  - {path: vmem, reason: VMEM banks; same-bank conflicts are Vmem invariants}",
        "invariants: {}",
        "relation: {mreg_banks: disjoint}",
        "pairs:",
    ]
    for a in order:
        for b in order:
            lines += [f"  {a}_{b}:",
                      f"    as: {{first: vpu.{a}, second: vpu.{b}}}",
                      f"    first: add",
                      f"    first_inputs: {{instruction: {instruction(a, 'first'):#010x}}}",
                      f"    second: add_hi",
                      f"    second_inputs: {{instruction: {instruction(b, 'second'):#010x}}}",
                      f"    gaps: 1..{nia[a] + 1 + MARGIN}"]
    if sweep is not None:
        records = {r["name"].split(".", 1)[1]: r for r in sweep["op_pairs"]}
        if set(records) != {f"{a}_{b}" for a in order for b in order}:
            raise ValueError("sweep must contain exactly every ordered VPU pair")
        lines += ["# Regression values used only by tests (full sweep); the extractor never reads them. stable_gap is the smallest",
                  "# gap from which every swept gap is accepted; next_issue_age is the first operation's (all.json).",
                  "expect:"]
        for a in order:
            for b in order:
                r = records[f"{a}_{b}"]
                lines.append(f"  {a}_{b}: {{min_gap: {r['min_gap']}, stable_gap: {r['stable_gap']}, next_issue_age: {nia[a]}}}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("facts", type=Path)
    parser.add_argument("sweep", type=Path, nargs="?")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    text = generate(json.loads(args.facts.read_text()),
                    json.loads(args.sweep.read_text()) if args.sweep else None)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
